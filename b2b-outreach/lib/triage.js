/**
 * triage.js — the vetting decision on a company, before any drafting happens.
 *
 * Tier 4 (prospect first-touch) requires `vetted_at`. That gate exists because
 * turning the tier on makes ~200 imported rows eligible at once, and they are
 * not equally ready: 23 donation-form orgs told us their size ranges and named
 * a contact, while ~120 CenterLink rows are a name slug and an email until the
 * research pass enriches them. Admission is deliberate, cohort by cohort.
 *
 * The vetting decisions, deliberately small:
 *   keep   → vetted_at = now         (admit to the queue)
 *   drop   → relationship_state=lost (never surfaces again; reason recorded)
 *   snooze → snoozed_until = date    (out of the queue until then)
 *
 * And the dispositions on a company already in play, which share this path so
 * the panel and the console tool can never mean different things by them:
 *   pause  → indefinitely not worked  (ours to reverse; reason required)
 *   on_me  → Jamie has claimed it     (still live, just not in today's queue)
 *   resume → back in the queue        (lifts whichever of the three is set)
 *
 * No draft is generated by any of them — the whole point is to clear a cohort
 * without paying for a draft per row.
 */

/**
 * Compute the update for one triage decision. Pure, so the tool, the bulk
 * script and the (future) panel all produce identical writes.
 *
 * @param action  'keep' | 'drop' | 'snooze'
 * @param opts    { reason, until (snooze only, YYYY-MM-DD), now }
 * @returns the b2b_companies patch
 */
function computeTriage(action, { reason = null, until = null, now = new Date(), source = 'operator', note = null } = {}) {
  switch (action) {
    case 'keep':
      // Reason is optional on keep — "yes, this one is fine" needs no essay.
      return { vetted_at: now.toISOString(), triage_reason: reason || null };
    case 'drop':
      if (!reason) throw new Error('drop requires a reason — an unexplained lost row gets re-litigated later');
      return { relationship_state: 'lost', triage_reason: reason, vetted_at: null };
    case 'snooze':
      // DEPRECATED 2026-08-27. Snooze asked the operator to invent a date for a
      // question the cadence already answers, and every real use turned out to
      // be "don't let the system start something yet" — which is the cadence's
      // own job. The nine rows that carried one were cleared to run on the
      // normal rhythm. Reading logic stays (pause shares deferredSince, and a
      // stray value must still behave), but nothing new can be set.
      throw new Error(
        'snooze is deprecated — the cadence decides when a company is next due, and the '
        + 'next-contact date on the company shows it. Use pause for an indefinite decision '
        + 'not to work a relationship, or leave it to the cadence.');
    case 'pause': {
      // Indefinite by design — the whole reason snooze does not fit is that
      // "not working Canadian retailers this year" has no date attached, and
      // inventing one produces a queue item on a day nobody chose.
      if (!reason) throw new Error('pause requires a reason — in six months "why is this paused?" is the only question that matters');
      // RETIRING a lead is this same operation with source 'cadence': the ladder
      // ran out of rungs and nobody ever answered. Deliberately not a new action
      // and emphatically not relationship_state='lost', which would claim they
      // went away or said no — false for someone who simply never replied, and
      // it destroys the state we would need to resume. What makes it a
      // retirement rather than an operator decision is who set it, which is
      // exactly what `source` records.
      return {
        outreach_paused_at: now.toISOString(),
        outreach_paused_reason: reason,
        outreach_paused_source: source,
      };
    }
    case 'on_me': {
      // "I owe them an answer, just not this minute." Unlike pause and snooze,
      // the work is still live — it moves to a list Jamie holds instead of
      // leaving the system.
      //
      // Deliberately just a stamp. It briefly took an optional note, on the
      // theory that the row needed to say what the claim was about — but the
      // relationship summary already computes a next step from the actual
      // conversation, which answers the same question better and without asking
      // for anything: a hand-typed note is written once and then decays, while
      // the next step is rebuilt as messages land. Claiming a company is a
      // one-click decision made while working the queue, and any prompt in front
      // of it is friction that makes you leave the row where it is instead,
      // which is the whole problem this exists to solve.
      //
      // A CADENCE claim is the exception, and it does not contradict the above:
      // that reasoning was about the cost of ASKING A HUMAN to type something,
      // and there is no click to slow down when the engine hands a relationship
      // over because it has run out of rungs. The note it writes carries only
      // the durable fact — a count and a date — so it cannot decay the way a
      // hand-typed intent does, while what to DO about it still comes from
      // relationship_next_step. `source` keeps the two kinds distinguishable so
      // the list can badge a hand-off rather than blur it into Jamie's own.
      return { on_me_at: now.toISOString(), on_me_source: source, on_me_note: note || null };
    }
    case 'resume':
      // Clears ALL of them, which is what the button means wherever it appears.
      // It used to null only the pause columns, so the "Resume now" rendered
      // beside a live snooze was a no-op — it reported success and the company
      // stayed snoozed. One action for "put this back in the queue" cannot know
      // which flavour the operator is looking at, so it lifts whatever is there.
      // Every column each deferral writes, including the source markers and the
      // hand-off note — a resume that left `on_me_source='cadence'` behind would
      // make the NEXT operator claim render as an engine hand-off, which is the
      // same class of bug as the version that nulled only the pause columns.
      return {
        outreach_paused_at: null, outreach_paused_reason: null, outreach_paused_source: null,
        snoozed_until: null, snoozed_at: null,
        on_me_at: null, on_me_source: null, on_me_note: null,
      };
    default:
      throw new Error(`unknown triage action '${action}' — expected keep, drop, snooze, pause, on_me or resume`);
  }
}

/** Apply a triage decision to one company. */
async function triageCompany(sb, { company_id, action, reason, until, now = new Date(), source = 'operator', note = null } = {}) {
  if (!company_id) throw new Error('company_id required');
  const { data: company, error } = await sb.from('b2b_companies')
    .select('id, name, relationship_state').eq('id', company_id).maybeSingle();
  if (error) throw new Error(error.message);
  if (!company) throw new Error(`company '${company_id}' not found`);

  const patch = computeTriage(action, { reason, until, now, source, note });
  const { error: uErr } = await sb.from('b2b_companies')
    .update({ ...patch, updated_at: now.toISOString() }).eq('id', company_id);
  if (uErr) throw new Error(uErr.message);

  // A pending draft is a chase waiting to be sent, so deciding not to chase has
  // to clear it. Leaving it behind does not merely look untidy: the panel merges
  // any company holding a pending draft back INTO the queue, carrying the tier
  // and reason frozen on the draft row, so a paused company reappeared at its
  // old tier with a stale "now due" explanation. Superseded rather than
  // dismissed, so the advisor's text survives as training signal.
  //
  // `on_me` is deliberately absent from that list: there the work is still
  // happening, and the draft is the thing you want in front of you when you pick
  // it back up. Throwing it away would mean paying for a second Opus call to
  // recreate what you had already read. The merge exclusion that keeps a paused
  // company out of the queue is what stops that surviving draft dragging the row
  // back in — see mergePendingDraftEntries.
  let draftsCleared = 0;
  if (action === 'pause' || action === 'snooze' || action === 'drop') {
    const { data, error: dErr } = await sb.from('b2b_drafts')
      .update({ status: 'superseded' })
      .eq('company_id', company_id).eq('status', 'pending').select('id');
    if (dErr) throw new Error(`clear pending drafts: ${dErr.message}`);
    draftsCleared = (data || []).length;
  }

  return { company_id, name: company.name, action, drafts_cleared: draftsCleared, ...patch };
}

module.exports = { computeTriage, triageCompany };
